/**
 * The baseline before the migration ledger (041): what a database at migration 040 should look like.
 *
 *   node tools/baseline.mjs          writes supabase/checks/040_baseline_check.sql and prints the hash
 *                                    that migration 041 expects (EXPECTED_040_HASH)
 *
 * Run 040_baseline_check.sql in the Supabase SQL editor (read-only) BEFORE 041. Each row it returns is a
 * difference between the live database and the repo's migrations 001–040. tests/migrations.test.mjs
 * fails if the committed check file or 041's hash is out of date.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { freshDb, fingerprint, strictHash, FINGERPRINT_SQL } from '../tests/support/supabase-stub.mjs';

export const CHECK_FILE = new URL('../supabase/checks/040_baseline_check.sql', import.meta.url);

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

export async function baselineAt40() {
  const db = await freshDb({ upTo: 40 });
  const rows = await fingerprint(db);
  const hash = await strictHash(db);
  await db.close();
  const sql = `-- READ-ONLY. Generated by tools/baseline.mjs from supabase/migrations/001–040: do not edit by hand.
--
-- Run this in Supabase → SQL Editor BEFORE migration 041. It changes nothing.
-- Each row is a difference between this database and what migrations 001–040 create:
--   blocks_041 = true   tables, columns, functions, policies, triggers. 041 refuses to run until these are
--                       resolved (or reviewed and accepted: see docs/MAINTAINING.md → "Before 041").
--   blocks_041 = false  grants to anon / authenticated. Recorded by 041, not blocking; review them anyway.
-- No rows = the live database matches the repo exactly.
with expected(kind, name, hash) as (values
${rows.map((r) => `  (${lit(r.kind)}, ${lit(r.name)}, ${lit(r.hash)})`).join(',\n')}
),
actual as (
${FINGERPRINT_SQL}
)
select coalesce(e.kind, a.kind) as kind, coalesce(e.name, a.name) as name,
       case when a.name is null then 'missing from this database'
            when e.name is null then 'not in the repo (extra here)'
            else 'different from the repo' end as problem,
       coalesce(e.kind, a.kind) <> 'grant' as blocks_041
from expected e full join actual a on a.kind = e.kind and a.name = e.name
where e.hash is distinct from a.hash
order by blocks_041 desc, 1, 2;

-- Hash that 041 expects for the blocking kinds: ${hash}
`;
  return { rows, hash, sql };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { rows, hash, sql } = await baselineAt40();
  writeFileSync(CHECK_FILE, sql);
  console.log(`Wrote ${fileURLToPath(CHECK_FILE)} (${rows.length} objects)`);
  console.log(`EXPECTED_040_HASH = ${hash}`);
}
